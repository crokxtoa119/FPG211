#!/usr/bin/env python3
"""Bundle the CSS sections into the single stylesheet the pages load.

Edit assets/css/styles.src.css (the ordered list of @import lines) and the
files in assets/css/sections/, then run this script. It writes
assets/css/styles.css, which is generated: do not edit it by hand.

    python3 tools/build_css.py            # write assets/css/styles.css
    python3 tools/build_css.py --check    # exit 1 if styles.css is stale
"""
import os
import re
import sys
from pathlib import Path

UI = Path(__file__).resolve().parent.parent / "ui"
CSS = UI / "assets" / "css"
SRC = CSS / "styles.src.css"
OUT = CSS / "styles.css"
FONT_CSS = UI / "assets" / "fonts" / "pretendard" / "pretendard.css"

IMPORT = re.compile(r'@import\s+url\(\s*["\']?([^"\')]+?)(?:\?[^"\')]*)?["\']?\s*\)\s*;')
HEADER = "/* Generated by tools/build_css.py from styles.src.css and sections/. Do not edit. */\n"


def rebase(css: str, from_dir: Path) -> str:
    """Rewrite relative url() targets so they resolve from assets/css/."""
    def fix(m):
        target = m.group(2)
        if re.match(r"(data:|https?:|/|#)", target):
            return m.group(0)
        resolved = (from_dir / target).resolve()
        rel = os.path.relpath(resolved, CSS.resolve()).replace(os.sep, "/")
        return f'url({m.group(1)}{rel}{m.group(1)})'

    return re.sub(r'url\((["\']?)([^"\')]+)\1\)', lambda m: fix(m), css)


def build() -> str:
    parts = [HEADER]
    for target in IMPORT.findall(SRC.read_text(encoding="utf-8")):
        path = (SRC.parent / target).resolve()
        text = path.read_text(encoding="utf-8")
        # A section may @import another stylesheet; inline it so the page
        # needs no second round trip. Only the font stylesheet does today.
        # Each file is rebased on its own, so swap the import for a token
        # first and put the rebased dependency back afterwards.
        deps = {}

        def stash(m):
            dep = (path.parent / m.group(1)).resolve()
            if dep != FONT_CSS.resolve():
                raise SystemExit(f"{path.name}: unexpected @import {m.group(1)}")
            token = f"/*@@dep{len(deps)}@@*/"
            deps[token] = rebase(dep.read_text(encoding="utf-8"), dep.parent)
            return token

        text = rebase(IMPORT.sub(stash, text), path.parent)
        for token, body in deps.items():
            text = text.replace(token, body)
        parts.append(f"/* ---- {path.name} ---- */\n{text}\n")
    return "".join(parts)


def main() -> int:
    css = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != css:
            print("styles.css is out of date: run python3 tools/build_css.py")
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(UI)} ({len(css.encode())} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
